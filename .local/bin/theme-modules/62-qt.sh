#!/usr/bin/env bash
set -euo pipefail
# priority: 62
# requires: qt5ct,qt6ct

qt5_dir="${XDG_CONFIG_HOME:-$HOME/.config}/qt5ct/colors"
qt6_dir="${XDG_CONFIG_HOME:-$HOME/.config}/qt6ct/colors"
kv_dir="${XDG_CONFIG_HOME:-$HOME/.config}/Kvantum/niri-rice"

mkdir -p "$qt5_dir" "$qt6_dir" "$kv_dir"

cat > "$qt5_dir/NiriRiceWal.conf" <<EOF
[ColorScheme]
active_colors=$foreground, $background, $color8, $color0, $accent, $foreground, $accent_blue, $accent_soft, $accent_urgent
disabled_colors=$color8, $background, $color8, $color0, $color8, $color8, $color8, $color8, $color8
inactive_colors=$foreground, $background, $color8, $color0, $accent, $foreground, $accent_blue, $accent_soft, $accent_urgent
EOF

cat > "$qt6_dir/NiriRiceWal.conf" <<EOF
[ColorScheme]
active_colors=$foreground, $background, $color8, $color0, $accent, $foreground, $accent_blue, $accent_soft, $accent_urgent
disabled_colors=$color8, $background, $color8, $color0, $color8, $color8, $color8, $color8, $color8
inactive_colors=$foreground, $background, $color8, $color0, $accent, $foreground, $accent_blue, $accent_soft, $accent_urgent
EOF

cat > "$kv_dir/niri-rice.kvconfig" <<EOF
[General]
author=roman
comment=Generated by niri-rice
theme=NiriRiceWal

[Colors:Window]
active=$background
inactive=$color0

[Colors:Button]
normal=$color0
hover=$accent_soft
focus=$accent

[Colors:Selection]
active=$accent
inactive=$accent_blue
EOF

qt5ct_conf="${XDG_CONFIG_HOME:-$HOME/.config}/qt5ct/qt5ct.conf"
qt6ct_conf="${XDG_CONFIG_HOME:-$HOME/.config}/qt6ct/qt6ct.conf"

if [[ -f "$qt5ct_conf" ]]; then
  if grep -q '^color_scheme_path=' "$qt5ct_conf"; then
    sed -i "s#^color_scheme_path=.*#color_scheme_path=$qt5_dir/NiriRiceWal.conf#" "$qt5ct_conf"
  else
    printf '\ncolor_scheme_path=%s/NiriRiceWal.conf\n' "$qt5_dir" >> "$qt5ct_conf"
  fi
fi

if [[ -f "$qt6ct_conf" ]]; then
  if grep -q '^color_scheme_path=' "$qt6ct_conf"; then
    sed -i "s#^color_scheme_path=.*#color_scheme_path=$qt6_dir/NiriRiceWal.conf#" "$qt6ct_conf"
  else
    printf '\ncolor_scheme_path=%s/NiriRiceWal.conf\n' "$qt6_dir" >> "$qt6ct_conf"
  fi
fi

kv_cfg="${XDG_CONFIG_HOME:-$HOME/.config}/Kvantum/kvantum.kvconfig"
mkdir -p "$(dirname "$kv_cfg")"
if [[ -f "$kv_cfg" ]]; then
  if grep -q '^theme=' "$kv_cfg"; then
    sed -i 's/^theme=.*/theme=niri-rice/' "$kv_cfg"
  else
    printf 'theme=niri-rice\n' >> "$kv_cfg"
  fi
else
  printf '[General]\ntheme=niri-rice\n' > "$kv_cfg"
fi
